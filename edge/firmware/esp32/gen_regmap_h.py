#!/usr/bin/env python3
"""Generate include/regmap.h from edge/regmap.json, so the firmware and the simulation share one map.

    python3 gen_regmap_h.py          # rewrite
    python3 gen_regmap_h.py --check  # exit 1 if out of date
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAP = json.loads((HERE.parent.parent / "regmap.json").read_text(encoding="utf-8"))


def render() -> str:
    out = ["// Generated by gen_regmap_h.py from edge/regmap.json. Do not edit.", "#pragma once", "#include <stdint.h>", "", "namespace regmap {"]
    out.append(f"constexpr uint16_t MAP_VERSION_VALUE = {MAP['version']};")
    out.append(f"constexpr uint8_t UNIT_ID = {MAP['unit_id']};")
    out.append("\n// Input registers (FC4)")
    for reg in MAP["input_registers"]:
        out.append(f"constexpr uint16_t IR_{reg['name']} = {reg['addr']};")
    out.append(f"constexpr uint16_t IR_COUNT = {max(r['addr'] for r in MAP['input_registers']) + 2};")
    out.append("\n// Coils (FC1, FC5)")
    for reg in MAP["coils"]:
        out.append(f"constexpr uint16_t COIL_{reg['name']} = {reg['addr']};")
    out.append("\n// Holding registers (FC3, FC16)")
    width = {"UINT": 1, "REAL": 2, "DINT": 2}
    for reg in MAP["holding_registers"]:
        out.append(f"constexpr uint16_t HR_{reg['name']} = {reg['addr']};")
    groups = {}
    for reg in MAP["holding_registers"]:
        groups.setdefault(reg["group"], []).append(reg)
    out.append("\n// Register blocks, written whole")
    for name, regs in groups.items():
        first = min(r["addr"] for r in regs)
        last = max(r["addr"] + width[r["type"]] for r in regs)
        out.append(f"constexpr uint16_t BLOCK_{name.upper()}_ADDR = {first};")
        out.append(f"constexpr uint16_t BLOCK_{name.upper()}_COUNT = {last - first};")
    out.append("\n// Setpoint limits and defaults")
    for reg in groups["setpoints"]:
        out.append(f"constexpr float {reg['name']}_DEFAULT = {float(reg['default'])}f;")
    first = groups["setpoints"][0]
    out.append(f"constexpr float SETPOINT_MIN = {float(first['min'])}f;")
    out.append(f"constexpr float SETPOINT_MAX = {float(first['max'])}f;")
    out.append("\n// Timing, ms")
    for key, value in MAP["timing"].items():
        out.append(f"constexpr uint32_t {key.upper()} = {value};")
    out.append(f"constexpr uint8_t MAX_CLIENTS = {MAP['max_clients']};")
    out.append("\n// ESP32 pins")
    for key, value in MAP["field_io_esp32"].items():
        out.append(f"constexpr uint8_t PIN_{key.upper().replace('_GPIO', '')} = {value};")
    out.append("}  // namespace regmap\n")
    return "\n".join(out)


def main() -> int:
    target = HERE / "include" / "regmap.h"
    text = render()
    if "--check" in sys.argv:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            print(f"{target} is out of date")
            return 1
        print("regmap.h matches regmap.json")
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
