"""Run a FUNCTION_BLOCK under real matiec and write its trace.json.

    python3 -m st2fb.reference_run --st corpus/X/program.st --stimulus corpus/X/stimulus.json --out build/X/matiec.json

This is the oracle, so it shares no code with the forward path. Its only knowledge of ST is the
small declaration scanner below, needed to name the interface for the generated test driver.
Everything the block computes comes from C generated by iec2c, compiled by gcc and executed, all
inside the docker/matiec.Dockerfile image. The host needs only Python and Docker.

Scan cycle, for scan i (0-based), in this order:
    1. __CURRENT_TIME := i * scan_ms
    2. write the VAR_INPUTs for scan i into the FB instance
    3. config_run__(i), which runs the FB body once
    4. read the VAR_OUTPUTs and record them with t_ms = i * scan_ms
So the first scan sees time 0, and the time seen by a scan equals its t_ms.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any

IMAGE = "st2fb-matiec:3a41303"
DOCKERFILE = Path(__file__).resolve().parent.parent / "docker" / "matiec.Dockerfile"
RUN_TIMEOUT_S = 10  # A mutated WHILE can loop forever, so the driver gets a hard limit.

# Exit codes of CONTAINER_SCRIPT, used to tell compile failures from runtime failures.
EXIT_IEC2C, EXIT_GCC, EXIT_RUN = 10, 11, 12

# -fwrapv: INT arithmetic is C int arithmetic in generated code, so overflow must be defined.
# -ffp-contract=off: stops fused multiply-add changing REAL results on some architectures.
# -D_____time_*: at this commit iec2c writes TIME + TIME in ST as a call to _____time_add, three
# underscores too many (print_binary_function in generate_c_base.cc adds them), and gcc rejects it. The two
# defines route the calls to the library's own __time_add and __time_sub.
# -lm: the math functions behind the iec_lib_* hooks defined in DRIVER_TEMPLATE.
# iec2c names its generated C files after the configuration and resource in wrap_program.
CONTAINER_SCRIPT = f"""
iec2c -I /opt/matiec/lib -T . wrapped.st > iec2c.log 2>&1 || exit {EXIT_IEC2C}
gcc -std=gnu11 -O1 -fwrapv -ffp-contract=off -w -D_____time_add=__time_add -D_____time_sub=__time_sub \
    -I/opt/matiec/lib/C -I. \
    driver.c ST2FB_CONFIG.c ST2FB_RES.c -lm -o driver > gcc.log 2>&1 || exit {EXIT_GCC}
timeout {RUN_TIMEOUT_S} ./driver < inputs.txt > outputs.txt 2> run.log || exit {EXIT_RUN}
"""

SUPPORTED_TYPES = {"BOOL", "INT", "DINT", "UINT", "REAL", "TIME"}
INT_RANGES = {"INT": (-(2**15), 2**15 - 1), "DINT": (-(2**31), 2**31 - 1), "UINT": (0, 2**16 - 1)}


class BadInput(Exception):
    """Bad input to the runner: malformed ST interface or stimulus."""


class CompileFailed(Exception):
    """iec2c or gcc rejected the program."""


class RunFailed(Exception):
    """The compiled program crashed, hung, or produced a value JSON cannot hold."""


@dataclass(frozen=True)
class Var:
    name: str
    type: str


@dataclass(frozen=True)
class Interface:
    fb_name: str
    inputs: list[Var]
    outputs: list[Var]


# Marks the block under test in a file that also declares helper function blocks. Without it, a file
# must hold exactly one FUNCTION_BLOCK. It is a comment, so matiec never sees it.
DUT_MARKER = re.compile(r"\(\*\s*st2fb:dut\s*\*\)\s*FUNCTION_BLOCK\s+(\w+)", flags=re.IGNORECASE)


def scan_interface(st_text: str) -> Interface:
    """Read the FB name and its VAR_INPUT and VAR_OUTPUT declarations.

    Only the text of the block under test is read, so a helper FUNCTION or FUNCTION_BLOCK in the same
    file adds nothing to the interface.
    """
    marked = DUT_MARKER.findall(st_text)
    if len(marked) > 1:
        raise BadInput(f"expected at most one st2fb:dut marker, found {len(marked)}")
    text = re.sub(r"\(\*.*?\*\)", " ", st_text, flags=re.DOTALL)
    names = re.findall(r"\bFUNCTION_BLOCK\s+(\w+)", text, flags=re.IGNORECASE)
    if marked:
        if marked[0] not in names:
            raise BadInput(f"the st2fb:dut marker names {marked[0]}, which is not a FUNCTION_BLOCK")
        names = marked
    if len(names) != 1:
        raise BadInput(f"expected exactly one FUNCTION_BLOCK, found {len(names)}")
    span = re.search(
        rf"\bFUNCTION_BLOCK\s+{re.escape(names[0])}\b(.*?)\bEND_FUNCTION_BLOCK\b", text, flags=re.DOTALL | re.IGNORECASE
    )
    text = span.group(1) if span else text

    def section(keyword: str) -> list[Var]:
        result: list[Var] = []
        for block in re.findall(rf"\b{keyword}\b(.*?)\bEND_VAR\b", text, flags=re.DOTALL | re.IGNORECASE):
            for declaration in block.split(";"):
                if not declaration.strip():
                    continue
                match = re.fullmatch(r"\s*([\w\s,]+?)\s*:\s*(\w+)\s*(:=.*)?", declaration, flags=re.DOTALL)
                if match is None:
                    raise BadInput(f"cannot read declaration: {declaration.strip()!r}")
                var_type = match.group(2).upper()
                if var_type not in SUPPORTED_TYPES:
                    raise BadInput(f"type {var_type} is outside the v1 scope")
                result += [Var(name.strip(), var_type) for name in match.group(1).split(",")]
        return result

    return Interface(names[0], section("VAR_INPUT"), section("VAR_OUTPUT"))


def wrap_program(st_text: str, interface: Interface, scan_ms: int) -> str:
    """Add the minimal PROGRAM and CONFIGURATION matiec needs to generate runnable code.

    The harness calls the FB with no arguments because the driver writes the FB's input
    variables directly, so the harness has no logic of its own that could alter behaviour.
    """
    return f"""{st_text}

PROGRAM ST2FB_HARNESS
VAR
  ST2FB_DUT : {interface.fb_name};
END_VAR
  ST2FB_DUT();
END_PROGRAM

CONFIGURATION ST2FB_CONFIG
  RESOURCE ST2FB_RES ON PLC
    TASK ST2FB_TASK(INTERVAL := T#{scan_ms}ms, PRIORITY := 0);
    PROGRAM ST2FB_INST WITH ST2FB_TASK : ST2FB_HARNESS;
  END_RESOURCE
END_CONFIGURATION
"""


DRIVER_TEMPLATE = """\
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include "iec_std_lib.h"
#include "accessor.h"
#include "POUS.h"

TIME __CURRENT_TIME;
extern ST2FB_HARNESS_data__ ST2FB_RES__ST2FB_INST;
void config_init__(void);
void config_run__(unsigned long tick);

/* matiec's iec_std_lib.h declares these and leaves them to the platform, so a program that uses
   REAL_TO_INT, REAL_TO_DINT (both through __real_round), ** or a function such as SQRT would not link.
   The library's own code still does the rounding. These only forward to the C library. */
double iec_lib_acos(double x) { return acos(x); }
double iec_lib_asin(double x) { return asin(x); }
double iec_lib_atan(double x) { return atan(x); }
double iec_lib_cos(double x) { return cos(x); }
double iec_lib_exp(double x) { return exp(x); }
double iec_lib_fmod(double x, double y) { return fmod(x, y); }
double iec_lib_log(double x) { return log(x); }
double iec_lib_log10(double x) { return log10(x); }
double iec_lib_pow(double x, double y) { return pow(x, y); }
double iec_lib_sin(double x) { return sin(x); }
double iec_lib_sqrt(double x) { return sqrt(x); }
double iec_lib_tan(double x) { return tan(x); }

static long long read_int(void) {
  long long value;
  if (scanf("%lld", &value) != 1) exit(3);
  return value;
}

static float read_real(void) {
  float value;
  if (scanf("%f", &value) != 1) exit(3);
  return value;
}

static TIME ms_to_time(long long ms) {
  TIME t;
  t.tv_sec = ms / 1000;
  t.tv_nsec = (ms % 1000) * 1000000;
  return t;
}

/* Rounds to the nearest ms: matiec builds TIME literals through doubles and truncates, so
   T#130ms is stored as 129999999 ns. See docs/CORPUS.md. */
static long long time_to_ms(TIME t) {
  long long ns = t.tv_sec * 1000000000LL + t.tv_nsec;
  return (ns >= 0 ? ns + 500000 : ns - 500000) / 1000000;
}

int main(void) {
  long long scan_ms = read_int();
  long long scans = read_int();
  config_init__();
  for (long long scan = 0; scan < scans; scan++) {
    __CURRENT_TIME = ms_to_time(scan * scan_ms);
@FEED@
    config_run__((unsigned long)scan);
@PRINT@
    putchar('\\n');
  }
  return 0;
}
"""


def _field(var: Var) -> str:
    return f"ST2FB_RES__ST2FB_INST.ST2FB_DUT.{var.name.upper()}.value"


def generate_driver(interface: Interface) -> str:
    feed = []
    for var in interface.inputs:
        if var.type == "REAL":
            source = "read_real()"
        elif var.type == "TIME":
            source = "ms_to_time(read_int())"
        else:
            source = f"({var.type})read_int()"
        feed.append(f"    {_field(var)} = {source};")

    show = []
    for var in interface.outputs:
        field = _field(var)
        if var.type == "REAL":
            # %.9g round-trips any IEEE 754 single.
            show.append(f'    printf("%.9g ", (double){field});')
        elif var.type == "TIME":
            show.append(f'    printf("%lld ", time_to_ms({field}));')
        else:
            show.append(f'    printf("%lld ", (long long){field});')

    return DRIVER_TEMPLATE.replace("@FEED@", "\n".join(feed)).replace("@PRINT@", "\n".join(show))


def _input_token(var: Var, value: Any, scan: int) -> str:
    where = f"scan {scan}, input {var.name}"
    if var.type == "BOOL":
        if not isinstance(value, bool):
            raise BadInput(f"{where}: expected a JSON bool, got {value!r}")
        return "1" if value else "0"
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise BadInput(f"{where}: expected a number, got {value!r}")
    if var.type == "REAL":
        return repr(float(value))
    if not isinstance(value, int):
        raise BadInput(f"{where}: {var.type} must be an integer, got {value!r}")
    if var.type in INT_RANGES:
        low, high = INT_RANGES[var.type]
        if not low <= value <= high:
            raise BadInput(f"{where}: {value} is out of range for {var.type}")
    return str(value)


def encode_inputs(interface: Interface, stimulus: dict[str, Any]) -> str:
    """Validate the stimulus against the contract and encode it for the driver's stdin."""
    scan_ms, scans = stimulus.get("scan_ms"), stimulus.get("scans")
    if not isinstance(scan_ms, int) or isinstance(scan_ms, bool) or scan_ms <= 0:
        raise BadInput(f"scan_ms must be a positive integer, got {scan_ms!r}")
    if not isinstance(scans, list):
        raise BadInput("'scans' must be a list")
    declared = {var.name for var in interface.inputs}
    lines = [f"{scan_ms} {len(scans)}"]
    for i, scan in enumerate(scans):
        if set(scan) != declared:
            raise BadInput(
                f"scan {i}: inputs {sorted(scan)} do not match VAR_INPUT {sorted(declared)}"
            )
        lines.append(" ".join(_input_token(var, scan[var.name], i) for var in interface.inputs))
    return "\n".join(lines) + "\n"


def decode_outputs(interface: Interface, text: str, stimulus: dict[str, Any]) -> dict[str, Any]:
    """Turn the driver's stdout into a trace, in the contract's shape."""
    scan_ms = stimulus["scan_ms"]
    rows = text.splitlines()
    if len(rows) != len(stimulus["scans"]):
        raise RunFailed(f"driver printed {len(rows)} scans, expected {len(stimulus['scans'])}")
    scans = []
    for i, row in enumerate(rows):
        tokens = row.split()
        if len(tokens) != len(interface.outputs):
            raise RunFailed(f"scan {i}: driver printed {len(tokens)} values, expected {len(interface.outputs)}")
        record: dict[str, Any] = {"t_ms": i * scan_ms}
        for var, token in zip(interface.outputs, tokens):
            if var.type == "BOOL":
                record[var.name] = token != "0"
            elif var.type == "REAL":
                value = float(token)
                if not math.isfinite(value):
                    raise RunFailed(f"scan {i}: {var.name} is {token}, which JSON cannot represent")
                record[var.name] = value
            else:
                record[var.name] = int(token)
        scans.append(record)
    return {
        "source": "matiec",
        "scan_ms": scan_ms,
        "outputs": [var.name for var in interface.outputs],
        "scans": scans,
    }


def ensure_image() -> None:
    present = subprocess.run(["docker", "image", "inspect", IMAGE], capture_output=True)
    if present.returncode != 0:
        print(f"building {IMAGE}, this takes a few minutes", file=sys.stderr)
        subprocess.run(
            ["docker", "build", "-f", str(DOCKERFILE), "-t", IMAGE, str(DOCKERFILE.parent)],
            check=True,
            stdout=sys.stderr,
        )


def _read_log(path: Path) -> str:
    return path.read_text(errors="replace")[-2000:] if path.exists() else ""


class Container:
    """A long-lived matiec container, so that a mutation campaign pays docker's start-up once."""

    def __enter__(self) -> "Container":
        self._directory = tempfile.TemporaryDirectory(prefix="st2fb-matiec-")
        self.directory = Path(self._directory.name)
        self.name = f"st2fb-matiec-{self.directory.name}".lower()
        command = [
            "docker", "run", "-d", "--rm", "--network", "none", "--name", self.name,
            "--user", f"{os.getuid()}:{os.getgid()}", "-v", f"{self.directory}:/work",
            IMAGE, "sleep", "infinity",
        ]  # fmt: skip
        subprocess.run(command, check=True, capture_output=True)
        return self

    def __exit__(self, *_: object) -> None:
        subprocess.run(["docker", "rm", "-f", self.name], capture_output=True)
        self._directory.cleanup()


def _compile_and_run(
    work: Path, docker_command: list[str], st_text: str, interface: Interface, stimulus: dict[str, Any], inputs: str
) -> dict[str, Any]:
    (work / "wrapped.st").write_text(wrap_program(st_text, interface, stimulus["scan_ms"]))
    (work / "driver.c").write_text(generate_driver(interface))
    (work / "inputs.txt").write_text(inputs)
    status = subprocess.run(docker_command + ["sh", "-c", CONTAINER_SCRIPT], capture_output=True, text=True).returncode
    if status == EXIT_IEC2C:
        raise CompileFailed("iec2c: " + _read_log(work / "iec2c.log"))
    if status == EXIT_GCC:
        raise CompileFailed("gcc: " + _read_log(work / "gcc.log"))
    if status == EXIT_RUN:
        raise RunFailed(f"driver crashed or exceeded {RUN_TIMEOUT_S}s: " + _read_log(work / "run.log"))
    if status != 0:
        raise RuntimeError(f"docker failed with status {status}")
    return decode_outputs(interface, (work / "outputs.txt").read_text(), stimulus)


def run_reference(st_text: str, stimulus: dict[str, Any], container: Container | None = None) -> dict[str, Any]:
    """Compile and run one program against one stimulus. Returns the trace."""
    interface = scan_interface(st_text)
    inputs = encode_inputs(interface, stimulus)
    if container is not None:
        with tempfile.TemporaryDirectory(dir=container.directory) as work:
            command = ["docker", "exec", "-w", f"/work/{Path(work).name}", container.name]
            return _compile_and_run(Path(work), command, st_text, interface, stimulus, inputs)
    with tempfile.TemporaryDirectory(prefix="st2fb-matiec-") as work:
        command = [
            "docker", "run", "--rm", "--network", "none",
            "--user", f"{os.getuid()}:{os.getgid()}",
            "-v", f"{work}:/work", "-w", "/work", IMAGE,
        ]  # fmt: skip
        return _compile_and_run(Path(work), command, st_text, interface, stimulus, inputs)


def format_trace(trace: dict[str, Any]) -> str:
    """One scan per line, so that traces diff well under version control."""
    header = {key: trace[key] for key in ("source", "scan_ms", "outputs")}
    head = json.dumps(header)[:-1]
    rows = ",\n".join("  " + json.dumps(scan) for scan in trace["scans"])
    return f'{head}, "scans": [\n{rows}\n]}}\n'


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run a FUNCTION_BLOCK under matiec and write trace.json.")
    parser.add_argument("--st", required=True)
    parser.add_argument("--stimulus", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)

    ensure_image()
    try:
        trace = run_reference(Path(args.st).read_text(), json.loads(Path(args.stimulus).read_text()))
    except (BadInput, CompileFailed, RunFailed) as exc:
        print(f"reference_run: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(format_trace(trace))
    print(f"wrote {out}: {len(trace['scans'])} scans, outputs {trace['outputs']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
